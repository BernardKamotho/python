# Boolean - This is a data type that either evaluates to true or false.

itsraining = False
print(itsraining)
print(type(itsraining))

paidloan = True
print(paidloan)
print(type(paidloan))

# Comparison operators: 
number1 = 2
number2 = 5
print("is number1 greater than number2?", number1 > number2)
print("is number1 less than number2?", number1 < number2)
print("is number1 equal to number2?", number1 == number2)
print("is number1 greater than or equal to number2?", number1 >= number2)
print("is number1 less than or equal to number2?", number1 <= number2)
print("is number1 not equal to number2?", number1 != number2)

# logical Operators.
# logical and - it returns true if and only if condition/statements evaluate to true.
print((3>1) and (7>6))

# Logical or- it evaluates true if one of the statements/conditions is true.
print((3>1) or (7<1) or (10>5))

# logical not
# It is used to negate a statement/a condition.
print(not(90 > 70))